export function foto(clave: string, w = 800, h = 600) {
  // fotos que el vendedor sube en esta sesión llegan como blob: o data:
  if (clave.startsWith("blob:") || clave.startsWith("data:")) return clave;
  const id = IDS[clave] ?? IDS.cem1;
  return `https://images.unsplash.com/${id}?w=${w}&h=${h}&fit=crop&q=72&auto=format`;
}

